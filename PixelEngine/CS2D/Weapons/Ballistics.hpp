inline const Profile &Get(WeaponId id) {
    const int index = std::clamp(static_cast<int>(id) - 2, 0, 33);
    return profiles[index];
}
inline float Spread(WeaponId id, float speedFraction, float scope, float accumulated, unsigned shot = 0) {
    const auto &p = Get(id);
    scope = std::clamp(scope, 0.0f, 1.0f);
    auto mode = [&](const std::array<float, 2> &v) { return v[0] + (v[1] - v[0]) * scope; };
    const float movement = std::clamp((speedFraction - .34f) / .66f, 0.0f, 1.0f);
    const float stage = id == WeaponId::Negev && shot < 3 ? 1.0f + (3 - shot) * .5f : 1.0f;
    return std::atan((mode(p.spread) + mode(p.stand) + mode(p.move) * movement + accumulated) * stage);
}
inline SDL_FPoint Recoil(WeaponId id, unsigned shot, float scope) {
    const auto &p = Get(id);
    std::mt19937 random(p.seed);
    std::uniform_real_distribution<float> sample(-1, 1);
    float x = 0, y = 0;
    const int mode = scope >= .5f ? 1 : 0;
    for (unsigned i = 0; i <= shot % 256; ++i) {
        const float angle =
            (p.angle[mode] + sample(random) * p.angleVariance[mode]) * Tuning::DegreesToRadians;
        const float magnitude =
            std::max(0.0f, p.magnitude[mode] + sample(random) * p.magnitudeVariance[mode]);
        x = x * .55f + std::sin(angle) * magnitude * .45f;
        y = y * .55f - std::cos(angle) * magnitude * .45f;
    }
    const float gain = std::tan(.6f * Tuning::DegreesToRadians) / 30;
    return {x * gain, y * gain};
}
inline SDL_FPoint RemoveKick(SDL_FPoint effective, SDL_FPoint kick) {
    const float scale = 1 - kick.x * kick.x - kick.y * kick.y;
    const float dot = effective.x * kick.x + effective.y * kick.y;
    const float squared = effective.x * effective.x + effective.y * effective.y;
    const float distance = (std::sqrt(dot * dot + scale * squared) - dot) / std::max(.001f, scale);
    return {effective.x - kick.x * distance, effective.y - kick.y * distance};
}

